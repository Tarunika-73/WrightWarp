"""Controlled vocabularies shared by MongoDB document models and Pydantic schemas.

Design note on provenance vs. quality (see docs/architecture/data_model.md
for the full rationale):

* ``DataProvenance`` answers "where did this observation come from" -
  REAL (collected from a live source), SYNTHETIC (fabricated for testing
  the pipeline), or SIMULATED (generated by a model/heuristic to stand in
  for a source that is not yet connected). This never changes after
  ingestion.
* ``QualityStatus`` answers "what has the data-quality pipeline decided
  about this observation" - RAW (untouched), VALIDATED, REJECTED,
  OUTLIER, DUPLICATE, or PROVISIONAL (passed basic checks but not yet
  confirmed against a second signal). This changes as the pipeline runs.

Mixing these into one field would make it impossible to represent, e.g.,
a REAL observation that is still RAW, or a SYNTHETIC observation that is
VALIDATED for pipeline-testing purposes. Keeping them orthogonal keeps
every future statistical claim honest about both axes independently.
"""
from enum import Enum


class DataProvenance(str, Enum):
    REAL = "REAL"
    SYNTHETIC = "SYNTHETIC"
    SIMULATED = "SIMULATED"


class QualityStatus(str, Enum):
    RAW = "RAW"
    VALIDATED = "VALIDATED"
    REJECTED = "REJECTED"
    OUTLIER = "OUTLIER"
    DUPLICATE = "DUPLICATE"
    PROVISIONAL = "PROVISIONAL"


class AvailabilityStatus(str, Enum):
    AVAILABLE = "AVAILABLE"
    SOLD_OUT = "SOLD_OUT"
    CANCELLED = "CANCELLED"
    NOT_FOUND = "NOT_FOUND"
    SCRAPE_FAILED = "SCRAPE_FAILED"
    INVALID_QUOTE = "INVALID_QUOTE"
    UNKNOWN = "UNKNOWN"


class CabinClass(str, Enum):
    ECONOMY = "ECONOMY"
    PREMIUM_ECONOMY = "PREMIUM_ECONOMY"
    BUSINESS = "BUSINESS"
    FIRST = "FIRST"


class SourceType(str, Enum):
    AIRLINE = "AIRLINE"
    OTA = "OTA"


class SearchRunStatus(str, Enum):
    """Checkpoint state of one collection attempt (one row per attempt).

    A batch of requests (e.g. one route across every T+ lead-time window)
    is simply several ``SearchRun`` rows processed independently - if one
    fails, the others keep whatever terminal status they already reached.
    ``BLOCKED`` and ``NO_RESULTS`` are kept distinct from ``FAILED`` so a
    compliance block or a genuinely empty search is never misread as a
    technical failure (see app.collection.contracts.CollectionOutcome).
    """

    PENDING = "PENDING"
    RUNNING = "RUNNING"
    RETRY = "RETRY"
    SUCCESS = "SUCCESS"
    PARTIAL = "PARTIAL"
    NO_RESULTS = "NO_RESULTS"
    FAILED = "FAILED"
    BLOCKED = "BLOCKED"
    SKIPPED = "SKIPPED"


class SourceStatus(str, Enum):
    """Operational readiness of a registered source - separate from ``enabled``.

    Registering a source (app.core.sources) never implies its adapter is
    implemented. Only ``IMPLEMENTED`` sources may be dispatched to by the
    collection service; every other status is a hard compliance stop.
    """

    CONFIGURED = "CONFIGURED"
    IMPLEMENTED = "IMPLEMENTED"
    DISABLED = "DISABLED"
    PENDING_REVIEW = "PENDING_REVIEW"


class RawObservationStatus(str, Enum):
    """Lifecycle of one raw payload captured by an adapter, prior to indexing."""

    COLLECTED = "COLLECTED"
    NORMALIZED = "NORMALIZED"
    PARSE_FAILED = "PARSE_FAILED"
    REJECTED = "REJECTED"


class CollectionErrorType(str, Enum):
    NETWORK_ERROR = "NETWORK_ERROR"
    TIMEOUT = "TIMEOUT"
    PARSER_ERROR = "PARSER_ERROR"
    SOURCE_UNAVAILABLE = "SOURCE_UNAVAILABLE"
    NO_RESULTS = "NO_RESULTS"
    RATE_LIMITED = "RATE_LIMITED"
    COMPLIANCE_BLOCKED = "COMPLIANCE_BLOCKED"
    INVALID_REQUEST = "INVALID_REQUEST"
    AUTH_ERROR = "AUTH_ERROR"
    UNKNOWN_ERROR = "UNKNOWN_ERROR"


class CollectionOutcome(str, Enum):
    """Distinguishes *why* a collection attempt ended, never conflating failure with zero flights."""

    SUCCESS = "SUCCESS"
    PARTIAL = "PARTIAL"
    FAILED = "FAILED"
    BLOCKED = "BLOCKED"
    NO_RESULTS = "NO_RESULTS"
